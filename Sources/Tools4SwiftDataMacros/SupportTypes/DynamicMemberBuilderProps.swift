import Foundation

/// A structure that encapsulates metadata about a type that conforms to the
/// `DynamicMemberBuilder` protocol.
///
/// `DynamicMemberBuilderProps` stores information about the final generated
/// type name and the name of the initializer that constructs it from a
/// transferable or configurable type. This is used by macros that generate
/// `DynamicMemberLookup`-based builders or proxies, enabling the synthesized
/// code to reference the correct types and initializers.
///
/// - Parameter declarationKind: Whether the generated declaration should be
///   a `var` (mutable) or `let` (immutable).
/// - Parameter finalProductName: The fully qualified name of the type that
///   will be generated by the macro.
/// - Parameter initFromTypeName: The name of the type from which the generated
///   product will be initialized (typically a transferable or configurable type).
struct DynamicMemberBuilderProps: Sendable {
    
    /// Indicates whether a generated declaration should be mutable or immutable.
    ///
    /// - mutable: The declaration is a `var`, allowing reassignment.
    /// - immutable: The declaration is a `let`, making it a constant.
    enum DeclarationKind: String {
        case mutable = "var"
        case immutable = "let"
    }
    
    let declarationKind: DeclarationKind
    let finalProductName: String
    let initFromTypeName: String
}
